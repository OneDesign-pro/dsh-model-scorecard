# Правки в форматировании дат: исходный код собирал «2026年9月27日», что в
# русском читается плохо, поэтому функция переписывается целиком.
DATE_FIXES = [
    (
        "      return parts[0] + '年' + Number(parts[1]) + '月' + Number(parts[2]) + '日 ' + week",
        "      return parts[2] + '.' + parts[1] + '.' + parts[0] + ' (' + week + ')'",
    ),
    (
        "      return Number(parts[0]) + '年' + Number(parts[1]) + '月'",
        "      return parts[1] + '.' + parts[0]",
    ),
    (
        "monthLabels.push({ left: j * 13, text: first.month === 0 ? first.year + '年1月' : (first.month + 1) + '月' })",
        "monthLabels.push({ left: j * 13, text: MONTHS_RU[first.month] })",
    ),
]

MONTHS_TABLE = (
    "    const MONTHS_RU = ['янв', 'фев', 'мар', 'апр', 'май', 'июн', "
    "'июл', 'авг', 'сен', 'окт', 'ноя', 'дек']\n"
)
ANCHOR = "    function humanDate(date) {"


def localized_literal(text: str, zh: str, ru: str) -> bool:
    """Уже переведено?"""
    return f"'{ru}'" in text and f"'{zh}'" not in text


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dry-run", action="store_true", help="ничего не писать")
    parser.add_argument("--revert", action="store_true", help="восстановить из бэкапа")
    args = parser.parse_args()

    if not TARGET.exists():
        print(f"не найден файл плагина: {TARGET}", file=sys.stderr)
        print("установлен ли dsh-usage-vendor-stats в профиле web?", file=sys.stderr)
        return 1

    if args.revert:
        if not BACKUP.exists():
            print(f"бэкап не найден: {BACKUP}", file=sys.stderr)
            return 1
        shutil.copyfile(BACKUP, TARGET)
        print(f"восстановлено из {BACKUP}")
        return 0

    text = TARGET.read_text(encoding="utf-8")
    before = text

    replaced = 0
    skipped = []
    for zh, ru in sorted(SIMPLE.items(), key=lambda kv: -len(kv[0])):
        literal = f"'{zh}'"
        count = text.count(literal)
        if count == 0:
            skipped.append(zh)
            continue
        text = text.replace(literal, f"'{ru}'")
        replaced += count

    for old, new in DATE_FIXES:
        if text.count(old) == 1:
            text = text.replace(old, new)
    if "MONTHS_RU" not in text and text.count(ANCHOR) == 1:
        text = text.replace(ANCHOR, MONTHS_TABLE + ANCHOR)

    leftover = re.findall(r"[\u4e00-\u9fff]+", text)
    print(f"заменено вхождений: {replaced}")
    print(f"иероглифов осталось:   {len(leftover)}")
    if skipped:
        print(f"не найдено (уже переведено или изменился исходник): {len(skipped)}")
        for zh in skipped[:10]:
            print(f"   {zh}")

    if leftover:
        print("ВНИМАНИЕ: в файле остались иероглифы:", " / ".join(sorted(set(leftover))[:20]))
        print("возможно, плагин обновился и появились новые строки")

    if args.dry_run:
        print("--dry-run: файл не изменён")
        return 0

    if not BACKUP.exists():
        BACKUP.write_text(before, encoding="utf-8")
        print(f"бэкап оригинала: {BACKUP}")

    TARGET.write_text(text, encoding="utf-8")
    print(f"записано: {TARGET}")
    print("перезагрузите страницу браузера целиком (Cmd+R)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
